static void test_sha256(void)
{
    uint8_t sha2_256_361byte_data_little[sha2_256_361byte_data_sz];
    uint8_t dst[SHA256_DIGEST_SIZE];
    int i = 0;
    uint32_t consumed = 0;
    uint32_t remaining = 0;
    uint8_t *ptr = sha2_256_361byte_data_little;
    sha2_ctx ctx;

    printf("SHA 256:");
    for (i = 0; i < sizeof(sha2_256_361byte_data_little); i++)
        sha2_256_361byte_data_little[i] = sha2_256_361byte_data[sha2_256_361byte_data_sz - 1 - i];

    memset(dst, 0, SHA256_DIGEST_SIZE);

    aml_hw_sha_init(&ctx, 0);

    remaining = sizeof(sha2_256_361byte_data_little);
    while (remaining > 0) {
        consumed = (remaining >= SHA256_BLOCK_SIZE)? SHA256_BLOCK_SIZE: remaining;
        remaining -= consumed;
        aml_hw_sha_update(&ctx, ptr, consumed, dst, (remaining > 0)? 0: 1);
        ptr += consumed;
    }

    if (!memcmp(dst, sha256_361byte_digest, sizeof(dst)))
        printf("PASS\n");
    else
        printf("FAIL\n");

    return;
}

