int32_t aml_hw_sha2_init(sha2_ctx *ctx, uint32_t is224)
{
	if (!ctx)
		return CRYPTO_ERROR_BAD_PARAMETERS;

	memset(ctx, 0, sizeof(*ctx));
	ctx->digest_len = is224 ? 224 : 256;

	return CRYPTO_ERROR_NO_ERROR;
}

int32_t aml_hw_sha2_update(sha2_ctx *ctx, const uint8_t *input, uint32_t ilen)
{
	uint32_t to_fill = 0;
	int32_t ret = CRYPTO_ERROR_NO_ERROR;
	uint32_t residue = 0;

	if (!ctx || !input || !ilen)
		return CRYPTO_ERROR_BAD_PARAMETERS;

	if (ctx->buf_len > 0) {
		to_fill = (SHA256_BLOCK_SIZE - ctx->buf_len) <= ilen ?
			(SHA256_BLOCK_SIZE - ctx->buf_len) : ilen;
		memcpy(ctx->buf + ctx->buf_len, input, to_fill);
		input += to_fill;
		ctx->buf_len += to_fill;
		ilen -= to_fill;

		if (ctx->buf_len == SHA256_BLOCK_SIZE) {
			ret = sha2_update_internal(ctx, ctx->buf, ctx->buf_len, NULL, 0);
			if (ret != CRYPTO_ERROR_NO_ERROR)
				return ret;
			ctx->buf_len = 0;
		} else
			return CRYPTO_ERROR_NO_ERROR;
	}

	residue = ilen % SHA256_BLOCK_SIZE;
	ret = sha2_update_internal(ctx, input, ilen - residue, NULL, 0);
	if (ret != CRYPTO_ERROR_NO_ERROR)
		return ret;
	input += ilen - residue;
	memcpy(ctx->buf, input, residue);
	ctx->buf_len = residue;

	return ret;
}

int32_t aml_hw_sha2_final(sha2_ctx *ctx, uint8_t *hash)
{
	return sha2_update_internal(ctx, ctx->buf, ctx->buf_len, hash, 1);
}

int32_t aml_hw_sha3_init(sha3_ctx *ctx, uint32_t mode)
{
	if (!ctx || mode >= SHA3_MAX)
		return CRYPTO_ERROR_BAD_PARAMETERS;

	memset(ctx, 0, sizeof(*ctx));
	ctx->mode = mode;

	switch (ctx->mode) {
		case SHA3_224:
			ctx->digest_len = SHA3_224_DIGEST_SIZE;
			ctx->block_size = SHA3_224_RATE;
			break;
		case SHA3_256:
			ctx->digest_len = SHA3_256_DIGEST_SIZE;
			ctx->block_size = SHA3_256_RATE;
			break;
		case SHA3_384:
			ctx->digest_len = SHA3_384_DIGEST_SIZE;
			ctx->block_size = SHA3_384_RATE;
			break;
		case SHA3_512:
			ctx->digest_len = SHA3_512_DIGEST_SIZE;
			ctx->block_size = SHA3_512_RATE;
			break;
		case SHA3_SHAKE_128:
			ctx->digest_len = 16;
			ctx->block_size = SHAKE_128_RATE;
			break;
		case SHA3_SHAKE_256:
			ctx->digest_len = 32;
			ctx->block_size = SHAKE_256_RATE;
			break;
		default:
			ctx->digest_len = 0;
			break;
	}

	return CRYPTO_ERROR_NO_ERROR;
}

int32_t aml_hw_sha3_update(sha3_ctx *ctx, const uint8_t *input, uint32_t ilen)
{
	int32_t ret = CRYPTO_ERROR_NO_ERROR;
#ifndef NO_BLOCK_BUFFERING_FOR_SHA3
	uint32_t to_fill = 0;
#endif
	uint32_t residue = 0;

	if (!ctx || !input || !ilen)
		return CRYPTO_ERROR_BAD_PARAMETERS;

#ifndef NO_BLOCK_BUFFERING_FOR_SHA3
	if (ctx->buf_len > 0) {
		to_fill = (ctx->block_size - ctx->buf_len) <= ilen ?
			(ctx->block_size - ctx->buf_len) : ilen;
		memcpy(ctx->buf + ctx->buf_len, input, to_fill);
		input += to_fill;
		ctx->buf_len += to_fill;
		ilen -= to_fill;

		if (ctx->buf_len == ctx->block_size) {
			ret = sha3_update_internal(ctx, ctx->buf, ctx->buf_len, NULL, 0, 0);
			if (ret != CRYPTO_ERROR_NO_ERROR)
				return ret;
			ctx->buf_len = 0;
		} else
			return CRYPTO_ERROR_NO_ERROR;
	}
#endif

#ifndef NO_BLOCK_BUFFERING_FOR_SHA3
	residue = ilen % ctx->block_size;
#endif
	ret = sha3_update_internal(ctx, input, ilen - residue, NULL, 0, 0);
	if (ret != CRYPTO_ERROR_NO_ERROR)
		return ret;

#ifndef NO_BLOCK_BUFFERING_FOR_SHA3
	input += ilen - residue;
	memcpy(ctx->buf, input, residue);
	ctx->buf_len = residue;
#endif

	return ret;
}

int32_t aml_hw_sha3_final(sha3_ctx *ctx, uint8_t *digest, uint32_t digest_size)
{
	int32_t ret = CRYPTO_ERROR_NO_ERROR;

	ret = sha3_update_internal(ctx, ctx->buf, ctx->buf_len, digest, digest_size, 1);
	if (ret != CRYPTO_ERROR_NO_ERROR) {
		printf("sha3 final failed\n");
		return ret;
	}

	if (ctx->mode >= SHA3_SHAKE_128)
		return sha3_shake_squeeze_internal(ctx, digest, digest_size);

	return ret;
}

